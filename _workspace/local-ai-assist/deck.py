# ── 잉크 수준 보조 (도해 부품이 아니라 사각+글자 묶음) ────────────────────────
def node(
    s,
    x,
    y,
    w,
    h,
    title,
    sub=None,
    fill=WHITE,
    line=LINE,
    tc=INK,
    sc=GRAY,
    ts=None,
    ss=None,
    a="c",
    valign="m",
):
    R(s, x, y, w, h, fill=fill, line=line)
    lines = [{"t": title, "s": ts or S["h"], "b": True, "c": tc, "a": a, "ls": 1.12}]
    if sub:
        lines.append({"t": sub, "s": ss or S["tiny"], "c": sc, "a": a, "sb": 2, "ls": 1.18})
    T(s, x + 0.09, y + 0.04, w - 0.18, h - 0.08, lines, valign=valign, name=f"node:{title}")


def cap(s, x, y, w, t, size=None, c=None, a="l", h=0.24, b=True):
    T(
        s,
        x,
        y,
        w,
        h,
        [{"t": t, "s": size or S["small"], "b": b, "c": c or INK, "a": a}],
        valign="m",
        name="소제목",
    )


def ah(s, x1, x2, y, color=GRAY, w=1.0):
    CONNECT(s, x1, y, x2, y, color=color, w=w)


def av(s, x, y1, y2, color=GRAY, w=1.0):
    CONNECT(s, x, y1, x, y2, color=color, w=w)


