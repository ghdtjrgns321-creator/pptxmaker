from collections import namedtuple

Box = namedtuple("Box", "x y w h")


def merged(layout, override):
    """LAYOUT 기본값 + 호출자 override. 없는 키를 새로 만들면 오타가 조용히 먹으므로 막는다."""
    if not override:
        return dict(layout)
    unknown = set(override) - set(layout)
    if unknown:
        raise KeyError(f"알 수 없는 layout 키: {sorted(unknown)} — 오타이거나 부품 계약 밖이다")
    return {**layout, **override}


def require(data, keys, name):
    """계약 ③ — 부품이 읽는 키가 data에 다 있는지. 없으면 조용한 빈칸 대신 시끄럽게 죽는다."""
    missing = [k for k in keys if k not in data or data[k] in (None, "", [], {})]
    if missing:
        raise ValueError(f"{name}: 필수 데이터 키 누락 {missing} — 부품은 글을 소유하지 않는다")
